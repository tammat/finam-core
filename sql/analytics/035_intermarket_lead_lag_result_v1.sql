CREATE TABLE IF NOT EXISTS analytics.intermarket_lead_lag_result_v1 (
    id BIGSERIAL PRIMARY KEY,
    discovery_run_id UUID NOT NULL,
    trial_number INTEGER NOT NULL,
    total_trials INTEGER NOT NULL,
    relationship_code TEXT NOT NULL,
    thesis TEXT NOT NULL,
    source_symbol TEXT NOT NULL,
    target_symbol TEXT NOT NULL,
    timeframe TEXT NOT NULL,
    impulse_bars INTEGER NOT NULL,
    lag_bars INTEGER NOT NULL,
    expected_direction SMALLINT NOT NULL CHECK (expected_direction IN (-1,1)),
    regime_group TEXT NOT NULL,
    signal_threshold NUMERIC NOT NULL,
    aligned_bars INTEGER NOT NULL,
    regime_coverage_ratio NUMERIC NOT NULL,
    validation_trades INTEGER NOT NULL,
    validation_profit_factor NUMERIC NOT NULL,
    validation_expectancy_bps NUMERIC NOT NULL,
    oos_trades INTEGER NOT NULL,
    oos_profit_factor NUMERIC NOT NULL,
    oos_expectancy_bps NUMERIC NOT NULL,
    oos_hit_rate NUMERIC NOT NULL,
    oos_information_coefficient NUMERIC NOT NULL,
    oos_max_drawdown_bps NUMERIC NOT NULL,
    folds_passed INTEGER NOT NULL,
    folds_total INTEGER NOT NULL,
    raw_p_value NUMERIC NOT NULL,
    adjusted_p_value NUMERIC NOT NULL,
    hypothesis_score NUMERIC NOT NULL,
    trust_status TEXT NOT NULL CHECK (trust_status IN ('VERIFIED','UNVERIFIED')),
    verdict_code TEXT NOT NULL CHECK (verdict_code IN ('OOS_PASS','OOS_FAIL','UNVERIFIED')),
    reason_code TEXT NOT NULL,
    promotion_allowed BOOLEAN NOT NULL DEFAULT false,
    catalog_version TEXT NOT NULL,
    source_version TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (discovery_run_id,relationship_code,impulse_bars,lag_bars,regime_group)
);

CREATE INDEX IF NOT EXISTS intermarket_lead_lag_result_v1_rank_idx
    ON analytics.intermarket_lead_lag_result_v1
    (discovery_run_id,verdict_code,hypothesis_score DESC);
